//! Hard mode / lock-in rules as a pure state machine (all times injected).
//!
//! Guarantees:
//! * the session end is a wall-clock UTC deadline, persisted by the daemon,
//! * the optional early-exit challenge is either typing a random string or
//!   waiting a cooldown,
//! * an emergency unlock ALWAYS succeeds after a long cooldown (>= 10 min).

use rand::RngExt;
use serde::{Deserialize, Serialize};

pub const MIN_EMERGENCY_COOLDOWN_MINS: u32 = 10;
pub const DEFAULT_EMERGENCY_COOLDOWN_MINS: u32 = 60;
pub const DEFAULT_EXIT_COOLDOWN_MINS: u32 = 20;
pub const CHALLENGE_LEN: usize = 48;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct HardModeConfig {
    /// Wall-clock deadline (unix seconds, UTC).
    pub deadline: i64,
    pub early_exit_challenge: bool,
    pub exit_cooldown_mins: u32,
    pub emergency_cooldown_mins: u32,
}

impl HardModeConfig {
    pub fn new(deadline: i64, early_exit_challenge: bool, exit_cooldown_mins: u32, emergency_cooldown_mins: u32) -> Self {
        Self {
            deadline,
            early_exit_challenge,
            exit_cooldown_mins: exit_cooldown_mins.max(1),
            emergency_cooldown_mins: emergency_cooldown_mins.max(MIN_EMERGENCY_COOLDOWN_MINS),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct HardModeState {
    /// Unix seconds at which an early-exit cooldown was requested.
    pub exit_requested_at: Option<i64>,
    /// Unix seconds at which an emergency unlock was requested.
    pub emergency_requested_at: Option<i64>,
    /// Currently displayed challenge string (generated by the daemon).
    pub challenge: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ExitDecision {
    /// Session may end now.
    Allowed,
    /// Not yet; seconds remaining for whichever route is closest.
    Denied { reason: String },
}

/// Random challenge string (alphanumeric, no look-alike chars).
pub fn generate_challenge() -> String {
    const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    let mut rng = rand::rng();
    (0..CHALLENGE_LEN).map(|_| ALPHABET[rng.random_range(0..ALPHABET.len())] as char).collect()
}

impl HardModeState {
    pub fn ensure_challenge(&mut self) -> &str {
        if self.challenge.is_none() {
            self.challenge = Some(generate_challenge());
        }
        self.challenge.as_deref().unwrap()
    }

    /// The deadline passing always ends the session.
    pub fn deadline_passed(cfg: &HardModeConfig, now: i64) -> bool {
        now >= cfg.deadline
    }

    /// Start (or restart) the early-exit cooldown.
    pub fn request_exit_cooldown(&mut self, now: i64) {
        self.exit_requested_at.get_or_insert(now);
    }
    pub fn cancel_exit_cooldown(&mut self) {
        self.exit_requested_at = None;
    }
    pub fn request_emergency(&mut self, now: i64) {
        self.emergency_requested_at.get_or_insert(now);
    }
    pub fn cancel_emergency(&mut self) {
        self.emergency_requested_at = None;
    }

    /// Seconds until the exit cooldown completes (None if not started).
    pub fn exit_cooldown_remaining(&self, cfg: &HardModeConfig, now: i64) -> Option<i64> {
        self.exit_requested_at.map(|t| (t + cfg.exit_cooldown_mins as i64 * 60 - now).max(0))
    }
    pub fn emergency_remaining(&self, cfg: &HardModeConfig, now: i64) -> Option<i64> {
        self.emergency_requested_at.map(|t| (t + cfg.emergency_cooldown_mins as i64 * 60 - now).max(0))
    }

    /// Try to end early by typing the challenge.
    pub fn try_challenge(&mut self, cfg: &HardModeConfig, typed: &str) -> ExitDecision {
        if !cfg.early_exit_challenge {
            return ExitDecision::Denied { reason: "Early-exit challenge is disabled for this session".into() };
        }
        match &self.challenge {
            Some(c) if c == typed.trim() => ExitDecision::Allowed,
            Some(_) => {
                // Wrong attempt: rotate the challenge so brute copying isn't useful.
                self.challenge = Some(generate_challenge());
                ExitDecision::Denied { reason: "Text did not match; a new challenge was generated".into() }
            }
            None => ExitDecision::Denied { reason: "No challenge is active".into() },
        }
    }

    /// Evaluate whether an end request via cooldown can complete.
    pub fn try_cooldown_exit(&self, cfg: &HardModeConfig, now: i64) -> ExitDecision {
        match self.exit_cooldown_remaining(cfg, now) {
            Some(0) => ExitDecision::Allowed,
            Some(r) => ExitDecision::Denied { reason: format!("{} s of cooldown remaining", r) },
            None => ExitDecision::Denied { reason: "Cooldown not started".into() },
        }
    }

    pub fn try_emergency(&self, cfg: &HardModeConfig, now: i64) -> ExitDecision {
        match self.emergency_remaining(cfg, now) {
            Some(0) => ExitDecision::Allowed,
            Some(r) => ExitDecision::Denied { reason: format!("{} s until emergency unlock", r) },
            None => ExitDecision::Denied { reason: "Emergency unlock not requested".into() },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> HardModeConfig {
        HardModeConfig::new(10_000, true, 20, 60)
    }

    #[test]
    fn emergency_floor_is_enforced() {
        let c = HardModeConfig::new(1, true, 1, 1);
        assert_eq!(c.emergency_cooldown_mins, MIN_EMERGENCY_COOLDOWN_MINS);
    }

    #[test]
    fn deadline() {
        assert!(!HardModeState::deadline_passed(&cfg(), 9_999));
        assert!(HardModeState::deadline_passed(&cfg(), 10_000));
    }

    #[test]
    fn challenge_flow() {
        let c = cfg();
        let mut st = HardModeState::default();
        let ch = st.ensure_challenge().to_string();
        assert_eq!(ch.len(), CHALLENGE_LEN);
        assert!(matches!(st.try_challenge(&c, "nope"), ExitDecision::Denied { .. }));
        let ch2 = st.challenge.clone().unwrap();
        assert_ne!(ch, ch2, "challenge rotates after failure");
        assert_eq!(st.try_challenge(&c, &ch2), ExitDecision::Allowed);
    }

    #[test]
    fn challenge_disabled() {
        let mut c = cfg();
        c.early_exit_challenge = false;
        let mut st = HardModeState::default();
        let ch = st.ensure_challenge().to_string();
        assert!(matches!(st.try_challenge(&c, &ch), ExitDecision::Denied { .. }));
    }

    #[test]
    fn cooldown_exit() {
        let c = cfg();
        let mut st = HardModeState::default();
        assert!(matches!(st.try_cooldown_exit(&c, 100), ExitDecision::Denied { .. }));
        st.request_exit_cooldown(100);
        st.request_exit_cooldown(200); // doesn't restart
        assert_eq!(st.exit_cooldown_remaining(&c, 100 + 1199), Some(1));
        assert!(matches!(st.try_cooldown_exit(&c, 100 + 1199), ExitDecision::Denied { .. }));
        assert_eq!(st.try_cooldown_exit(&c, 100 + 1200), ExitDecision::Allowed);
        st.cancel_exit_cooldown();
        assert!(matches!(st.try_cooldown_exit(&c, 100 + 5000), ExitDecision::Denied { .. }));
    }

    #[test]
    fn emergency_always_works_even_without_challenge() {
        let mut c = cfg();
        c.early_exit_challenge = false;
        let mut st = HardModeState::default();
        st.request_emergency(0);
        assert!(matches!(st.try_emergency(&c, 3599), ExitDecision::Denied { .. }));
        assert_eq!(st.try_emergency(&c, 3600), ExitDecision::Allowed);
    }

    #[test]
    fn state_roundtrips_json() {
        let mut st = HardModeState::default();
        st.ensure_challenge();
        st.request_emergency(5);
        let j = serde_json::to_string(&st).unwrap();
        assert_eq!(serde_json::from_str::<HardModeState>(&j).unwrap(), st);
    }
}
